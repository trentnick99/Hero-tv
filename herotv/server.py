def watch_heartbeat(app, idle_s=150, never_s=300):
    """Quiet mode (no console window): turn the TV off by itself once its window has been closed for a while."""
    def loop():
        began = prev = time.monotonic()
        while True:
            time.sleep(5)
            now = time.monotonic()
            if now - prev > 30:             # the computer was asleep: do not count that as "window closed"
                if app.last_hb is not None:
                    app.last_hb = now
                began = now
            prev = now
            quiet_for = now - (app.last_hb if app.last_hb is not None else began)
            if quiet_for > (idle_s if app.last_hb is not None else never_s):
                print("TV window closed - shutting down.", flush=True)
                app.stop()
                return
    threading.Thread(target=loop, daemon=True, name="heartbeat-watch").start()


def serve(cfg):
    # The API intentionally has no login system. Refuse accidental LAN exposure unless
    # the operator explicitly opts in and accepts that other LAN clients can control it.
    if cfg.host not in ("127.0.0.1", "localhost", "::1") and os.environ.get("HEROTV_ALLOW_LAN", "0") != "1":
        raise SystemExit("Refusing non-local bind without authentication. Set HEROTV_HOST=127.0.0.1, or explicitly set HEROTV_ALLOW_LAN=1 only on a trusted network.")
    try:
        channels_api.ensure_builtin(cfg)              # e.g. For You (1.13) for people who had HERO TV before
    except Exception:
        traceback.print_exc()
    app = App(cfg)
    c = app.db()
    with open(cfg.channels_file, encoding="utf-8-sig") as f:
        S.sync_channels(c, json.load(f)["channels"], tz=app.tz)
    c.execute("DELETE FROM prefs WHERE key LIKE 'remote\\_%' ESCAPE '\\'")    # settings (PIN etc.) of the removed phone remote
    c.commit()
    S.extend_all(c, time.time(), app.horizon(), rebuild=True, tz=app.tz, resume=True)   # carry on where you left off
    c.close()
    app.maintain_forever()
    app.watch_library_forever()
    if dlna.enabled():
        try:
            app.dlna.start()
            print(f"TV media players can find '{dlna.friendly_name()}' on port {dlna.port(cfg)}", flush=True)
        except ValueError as e:
            print("TV media players: " + str(e), flush=True)
    if R.enabled():
        try:
            port = app.start_lan()
            print("Other devices: " + ", ".join(f"http://{a}:{port}" for a in R.lan_addresses()), flush=True)
        except ValueError as e:
            print("Other devices: " + str(e), flush=True)
    inbox.watch_forever(cfg)
    from . import selfupdate
    app.update_note = selfupdate.take_last_error()
    if os.environ.get("HEROTV_NO_UPDATE_CHECK") != "1":
        selfupdate.watch_forever()
    srv = _TVServer((cfg.host, cfg.port), make_handler(app))
    srv.daemon_threads = True
    app.stop = lambda: threading.Thread(target=srv.shutdown, daemon=True).start()
    thumbs.start_background(cfg, connect)
    art.start_background(cfg, connect)
    if os.environ.get("HEROTV_QUIET") == "1":
        watch_heartbeat(app)
    print(f"HERO TV on http://{cfg.host}:{srv.server_address[1]}  tz={cfg.tz}", flush=True)
    srv.serve_forever()
