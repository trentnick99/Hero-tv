def _inside(path, root):
    """Is path inside the folder root? (A plain prefix test would also accept a sibling like 'Media2' for root 'Media'.)"""
    try:
        r = os.path.normcase(os.path.abspath(root))
        return os.path.normcase(os.path.commonpath([os.path.abspath(path), os.path.abspath(root)])) == r
    except ValueError:                                     # another drive
        return False
