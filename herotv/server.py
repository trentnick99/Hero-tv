        def inbox_files(self, c, limit=15):
            """Videos waiting in the Inbox, with what TMDB already knows about each (no lookups here)."""
            d = inbox.inbox_dir(app.cfg)
            out = []
            if not os.path.isdir(d):
                return out
            exts = L.EXTS | inbox._convertible()
            shown = set()
            for dp, dn, fn in os.walk(d):
                dn[:] = sorted(x for x in dn if not x.startswith("."))
                for f in sorted(fn):
                    if f.startswith(".") or f.lower().endswith(inbox.PARTIAL) or os.path.splitext(f)[1].lower() not in exts:
                        continue
                    stem = os.path.splitext(f)[0]
                    g = L._guess([stem], stem)
                    about = art.describe(art.facts_for(c, app.cfg, stem, cached_only=True))
                    try:
                        from . import sortrules
                        suggest = [ch["id"] for ch in insights.series_channels(c, sortrules.load(app.cfg, write=False)[1], stem)]
                    except Exception:
                        suggest = []
                    rel = os.path.relpath(os.path.join(dp, f), d).replace(os.sep, "/")
                    if os.path.join(dp, f) in shown:
                        continue                             # already listed as part of its show or pack
                    group = self.inbox_group(rel)
                    shown.update(group)
                    out.append({"file": rel, "pack": self.pack_name(rel), "group": len(group),
                                "title": (g["series"] + " - " if g["series"] else "") + g["title"] + (f" ({g['year']})" if g["year"] and not g["series"] else ""),
                                "about": about, "suggest": suggest[:1]})
                    if len(out) >= limit:
                        return out
            return out

        @staticmethod
        def pack_name(rel):
            """A good name for a new channel from an Inbox file: its show name, else the folder it came in, else its title."""
            stem = os.path.splitext(os.path.basename(rel))[0]
            g = L._guess([stem], stem)
            if g["series"]:
                return g["series"]
            if "/" in rel:
                return L.tidy(rel.split("/")[0])[0]
            return g["title"]

        def inbox_group(self, rel):
            """Inbox files that go together with this one: the same show, or the same folder dropped into the Inbox."""
            d = inbox.inbox_dir(app.cfg)
            stem = os.path.splitext(os.path.basename(rel))[0]
            key = insights._n(L._guess([stem], stem)["series"])
            top = rel.split("/")[0] if "/" in rel else None
            out = []
            exts = L.EXTS | inbox._convertible()
            for dp, dn, fn in os.walk(d):
                dn[:] = [x for x in dn if not x.startswith(".")]
                for f in fn:
                    if f.startswith(".") or f.lower().endswith(inbox.PARTIAL) or os.path.splitext(f)[1].lower() not in exts:
                        continue
                    r = os.path.relpath(os.path.join(dp, f), d).replace(os.sep, "/")
                    st = os.path.splitext(f)[0]
                    if r == rel or (top and r.split("/")[0] == top and "/" in r) or (key and insights._n(L._guess([st], st)["series"]) == key):
                        out.append(os.path.join(dp, f))
            return sorted(out)

