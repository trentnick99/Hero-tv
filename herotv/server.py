        def change_channels(self, c, body):
            """Apply one Settings > Channels change and put the new channel list to work at once."""
            res = channels_api.update(app.cfg, body)
            try:
                with app.scan_lock, open(app.cfg.channels_file, encoding="utf-8-sig") as f:
                    S.sync_channels(c, json.load(f)["channels"], tz=app.tz)
                    S.extend_all(c, time.time(), app.horizon(), tz=app.tz)
            except (ValueError, KeyError, OSError) as e:
                channels_api.revert(app.cfg)
                with app.scan_lock, open(app.cfg.channels_file, encoding="utf-8-sig") as f:
                    S.sync_channels(c, json.load(f)["channels"], tz=app.tz)
                raise ValueError(f"That change could not be used, so it was undone ({e}).")
            app.lib_version += 1
            app.lib_note = "channels updated"
            return res

