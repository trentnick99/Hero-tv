def empty_channel_ids(c):
    """Ids of TV channels with no playable video that matches them (they are hidden until something arrives)."""
    media = c.execute("SELECT franchise,tags,series,year,runtime_s,episode FROM media WHERE available=1 AND verified=1 AND playable=1").fetchall()
    out = set()
    for ch in S.channels(c):
        if (ch["kind"] or "tv") == "foryou":
            if not media:
                out.add(ch["id"])
            continue
        if (ch["kind"] or "tv") != "tv":
            continue
        rules, _blocks = S._spec(ch)
        if not any(S.matches(rules, m) for m in media):
            out.add(ch["id"])
    return out


class App:
    def __init__(self, cfg):
        self.cfg, self.tz = cfg, cfg.tz
        get_tz(cfg.tz)  # fail fast on a bad timezone
        self.scan_lock = threading.Lock()
        self.lan_srv = None          # the home-network listener (Settings > Other devices), None when off
        self.lan_lock = threading.Lock()
        self.dlna = dlna.Server(self)  # TV media players (Settings > Other devices), started only when switched on
        self.upload_token = secrets.token_urlsafe(24)   # only the TV page itself can read this (other sites cannot read our replies)
        self.last_hb = None          # monotonic time of the TV page's last heartbeat (quiet mode only)
        self.stop = None             # set by serve(): function that shuts the server down
        self.errors = {}  # media_id -> [timestamps] of client playback errors
        self.lib_version = 0         # bumped whenever the library changes by itself; the TV page reloads its lists
        self.lib_note = ""

    def library_signature(self):
        """Cheap fingerprint of the media folder (names, sizes, dates of videos and .hero.json files), or None if unreachable."""
        root = os.path.abspath(str(self.cfg.media_dir))
        if not os.path.isdir(root):
            return None
        h, n = hashlib.md5(), 0
        for dp, dn, fn in os.walk(root):
            dn[:] = sorted(d for d in dn if not d.startswith("."))
            for f in sorted(fn):
                if os.path.splitext(f)[1].lower() in L.EXTS or f.endswith(".hero.json"):
                    try:
                        st = os.stat(os.path.join(dp, f))
                    except OSError:
                        continue
                    h.update(f"{dp}|{f}|{st.st_size}|{int(st.st_mtime)}\n".encode("utf-8", "replace"))
                    n += 1
        return f"{n}:{h.hexdigest()}"

    def refresh_library(self):
        """Scan for added / removed / changed videos and re-plan the schedule. Returns the scan stats."""
        c = self.db()
        try:
            with self.scan_lock:
                st = L.scan(c, self.cfg.media_dir)
                S.extend_all(c, time.time(), self.horizon(), rebuild=True, tz=self.tz)
        finally:
            c.close()
        thumbs.start_background(self.cfg, connect)
        art.start_background(self.cfg, connect)
        return st

    def watch_library_forever(self, every=None):
        """Notice new/removed videos by itself (no rescan key needed). A change must stay the same for one extra
        check before it is applied, so a file that is still being copied in is not read half-finished."""
        every = every or float(os.environ.get("HEROTV_WATCH_S", "60"))

        def loop():
            applied = pending = None
            try:
                applied = self.library_signature()
            except Exception:
                pass
            while True:
                time.sleep(every)
                try:
                    t0 = time.monotonic()
                    sig = self.library_signature()
                    slow = time.monotonic() - t0 > 3          # a big or sleepy drive: look less often
                    if sig is not None and sig != applied:
                        if sig == pending:
                            st = self.refresh_library()
                            applied, pending = sig, None
                            bits = [f"{st[k]} {w}" for k, w in (("added", "new"), ("missing", "removed")) if st.get(k)]
                            self.lib_note = ", ".join(bits) or "updated"
                            self.lib_version += 1
                        else:
                            pending = sig
                    else:
                        pending = None
                    if slow:
                        time.sleep(every * 4)
                except Exception:
                    traceback.print_exc()
        threading.Thread(target=loop, daemon=True, name="library-watcher").start()

    def db(self):
        return connect(self.cfg.db_path)

    def start_lan(self):
        """Open the home-network listener (port 8788). Every request on it needs a paired device."""
        with self.lan_lock:
            if self.lan_srv is not None:
                return R.lan_port(self.cfg)
            try:
                srv = _TVServer(("0.0.0.0", R.lan_port(self.cfg)), make_handler(self, remote=True))
            except OSError as e:
                raise ValueError(f"Port {R.lan_port(self.cfg)} is busy on this PC, so other devices cannot connect ({e}).")
            srv.daemon_threads = True
            threading.Thread(target=srv.serve_forever, daemon=True, name="lan").start()
            self.lan_srv = srv
            return srv.server_address[1]

    def stop_lan(self):
        with self.lan_lock:
            srv, self.lan_srv = self.lan_srv, None
        if srv is not None:
            srv.shutdown()
            srv.server_close()

    def horizon(self):
        return self.cfg.horizon_h * 3600

    def refresh_for_you(self, c):
        """Re-plan the For You channel (what has not aired yet) when you have watched something since last time."""
        from . import insights
        sig = insights.history_signature(c)
        if sig == getattr(self, "_fy_sig", None):
            return False
        first = getattr(self, "_fy_sig", None) is None
        if not first and time.monotonic() - getattr(self, "_fy_at", 0) < 1800:
            return False                                 # at most every half hour, so the guide does not keep changing
        self._fy_sig, self._fy_at = sig, time.monotonic()
        if first:
            return False                                 # just started: the schedule was planned moments ago
        for ch in S.channels(c):
            if (ch["kind"] or "tv") == "foryou":
                S.rebuild_future(c, ch, time.time(), self.horizon(), tz=self.tz)
        return True

    def maintain_forever(self, every=300):
        def loop():
            while True:
                try:
                    c = self.db()
                    try:
                        S.extend_all(c, time.time(), self.horizon(), tz=self.tz)
                        self.refresh_for_you(c)
                        try:
                            from . import backup
                            made = backup.auto(self.cfg, c)
                            if made:
                                print("Weekly backup saved: " + str(made), flush=True)
                        except Exception:
                            traceback.print_exc()       # a backup problem never stops the TV
                    finally:
                        c.close()
                except Exception:
                    traceback.print_exc()
                time.sleep(every)
        threading.Thread(target=loop, daemon=True, name="schedule-maintainer").start()


class _TVServer(ThreadingHTTPServer):
    request_queue_size = 128
    daemon_threads = True

    def server_bind(self):
        # The standard version looks up this computer's full network name (getfqdn), which can hang for half a
        # minute on some networks. Nothing here needs it.
        import socketserver
        socketserver.TCPServer.server_bind(self)
        host, port = self.server_address[:2]
        self.server_name, self.server_port = str(host), port


def make_handler(app, remote=False):
    class H(BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.1"
        server_version = "HeroTV/1"
        is_remote = remote            # True on the home-network port: paired devices only, watch-only
        device = None

        def log_message(self, fmt, *a):
            if os.environ.get("HEROTV_ACCESS_LOG"):
                super().log_message(fmt, *a)

        # -- helpers
        def send_json(self, obj, code=200):
            b = json.dumps(obj).encode()
            self.send_response(code)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(b)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(b)

        def end_headers(self):
            # Defense-in-depth for the local kiosk UI and API.
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("X-Frame-Options", "DENY")
            self.send_header("Referrer-Policy", "no-referrer")
            self.send_header("Permissions-Policy", "camera=(), microphone=(), geolocation=()")
            super().end_headers()

        def body(self):
            raw_n = self.headers.get("Content-Length", "0")
            try:
                n = int(raw_n)
            except (TypeError, ValueError):
                raise ValueError("invalid content length")
            if n < 0 or n > MAX_BODY_BYTES:
                self.drain(n)
                raise ValueError("request body too large")
            self._body_done = True
            raw = self.rfile.read(n) if n else b"{}"
            try:
                data = json.loads(raw)
            except (ValueError, UnicodeDecodeError) as exc:
                raise ValueError("invalid JSON") from exc
            if not isinstance(data, dict):
                raise ValueError("JSON body must be an object")
            return data

        def drain(self, n):
            """Discard an unwanted request body (bounded) so the connection can stay in sync, else close it."""
            self._body_done = True
            if 0 < n <= 1 << 20:
                self.rfile.read(n)
            elif n != 0:
                self.close_connection = True

        def host_ok(self):
            # Blocks DNS-rebinding: a web page cannot reach this loopback-only API under another hostname.
            if os.environ.get("HEROTV_ALLOW_LAN") == "1":
                return True
            h = (self.headers.get("Host") or "").lower()
            if not h.endswith("]"):
                h = h.rsplit(":", 1)[0]
            return h in ("127.0.0.1", "localhost", "[::1]")

        def do_GET(self):
            self.dispatch("GET")

        def do_POST(self):
            self.dispatch("POST")

        def remote_gate(self, method):
            """Network port only. True when the request may go on; otherwise the reply has been sent."""
            u = urlparse(self.path)
            p = u.path
            n = int(self.headers.get("Content-Length") or 0)
            if not R.enabled() or not R.host_ok(self.headers.get("Host")):
                self.drain(n)
                self.send_json({"error": "not available"}, 403)
                return False
            if p in ("/pair", "/pair.html"):
                self.static("pair.html")
                return False
            if p == "/api/pair":
                if method != "POST" or self.headers.get("Content-Type", "").split(";")[0].strip().lower() != "application/json":
                    self.drain(n)
                    self.send_json({"error": "use the pairing page"}, 400)
                    return False
                c = app.db()
                try:
                    tok, mk = R.pair(c, self.body().get("code"), R.device_name(self.headers.get("User-Agent")), self.client_address[0])
                except ValueError as e:
                    return self.send_json({"error": str(e)}, 403) and False
                finally:
                    c.close()
                b = json.dumps({"ok": True}).encode()
                self.send_response(200)
                self.send_header("Content-Type", "application/json; charset=utf-8")
                self.send_header("Set-Cookie", f"{R.COOKIE}={tok}; Path=/; Max-Age=31536000; HttpOnly; SameSite=Strict")
                self.send_header("Content-Length", str(len(b)))
                self.end_headers()
                self.wfile.write(b)
                return False
            c = app.db()
            try:
                dev = R.device_for(c, R.cookie_token(self.headers.get("Cookie")))
                if dev is None and method == "GET" and p.startswith(("/media/", "/thumb/", "/poster/", "/sub/")):
                    dev = R.device_for_media_key(c, (parse_qs(u.query).get("k") or [""])[0])   # e.g. a TV fetching over AirPlay
                if dev is not None:
                    R.touch(c, dev, self.client_address[0])
            finally:
                c.close()
            if dev is None:
                self.drain(n)
                if p in ("/", "/index.html"):
                    self.send_response(302)
                    self.send_header("Location", "/pair")
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                else:
                    self.send_json({"error": "pair this device first"}, 401)
                return False
            self.device = dev
            if p.startswith("/api/"):
                name = p[5:]
                ok = (name in R.REMOTE_POST_API) if method == "POST" else (name in R.REMOTE_GET_API or name.startswith(R.REMOTE_GET_API_PREFIX))
                if not ok:
                    self.drain(n)
                    self.send_json({"error": "That only works on the PC."}, 403)
                    return False
            return True

        def dispatch(self, method):
            self._body_done = False
            try:
                if self.is_remote and not self.remote_gate(method):
                    return
                if not self.is_remote and not self.host_ok():
                    self.drain(int(self.headers.get("Content-Length") or 0))
                    return self.send_json({"error": "unexpected Host header"}, 403)
                if method == "POST" and urlparse(self.path).path == "/api/upload" and not self.is_remote:
                    return self.upload(parse_qs(urlparse(self.path).query))
                if method == "POST" and self.headers.get("Content-Type", "").split(";")[0].strip().lower() != "application/json":
                    # Browsers send other types cross-site without a CORS preflight, so refuse them (CSRF guard).
                    self.drain(int(self.headers.get("Content-Length") or 0))
                    return self.send_json({"error": "Content-Type must be application/json"}, 415)
                self.route(urlparse(self.path), method)
            except ConnectionError:   # incl. Windows ConnectionAbortedError when the browser drops a video stream
                pass
            except ValueError as exc:
                self.send_json({"error": str(exc)}, 400)
            except (KeyError, TypeError, OverflowError) as exc:
                self.send_json({"error": "invalid request"}, 400)
            except Exception:
                traceback.print_exc()
                self.send_json({"error": "internal"}, 500)
            finally:
                if method == "POST" and not self._body_done:
                    self.close_connection = True   # unread body left on the socket: do not reuse the connection

        def action(self, c, name):
            """Buttons on the Settings screen. Fixed list - the page can never name a path or a program."""
            from . import backup, library as LIB
            from .config import settings_file
            folders = {"open-media": app.cfg.media_dir, "open-inbox": inbox.inbox_dir(app.cfg),
                       "open-backups": backup.default_dir(), "open-logs": settings_file().parent}
            if name in folders:
                d = str(folders[name])
                os.makedirs(d, exist_ok=True)
                if os.name == "nt":
                    os.startfile(d)               # opens Explorer on your own PC
                    return {"ok": True, "message": "Opened."}
                return {"ok": True, "message": "Folder: " + d}
            if name == "rescan":
                with app.scan_lock:
                    st = LIB.scan(c, app.cfg.media_dir)
                    S.extend_all(c, time.time(), app.horizon(), rebuild=True, tz=app.tz)
                thumbs.start_background(app.cfg, connect)
                art.start_background(app.cfg, connect)
                return {"ok": True, "message": f"Library checked: {st.get('added', 0)} new, {st.get('missing', 0)} removed."}
            if name == "backup":
                path = backup.make(app.cfg, c)
                return {"ok": True, "message": "Backup saved: " + str(path)}
            raise ValueError("unknown action")

