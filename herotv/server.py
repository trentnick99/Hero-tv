        def report_error(self, c, mid, now, certain=False):
            m = c.execute("SELECT * FROM media WHERE id=?", (mid,)).fetchone()
            if m is None:
                return {"action": "none"}
            hits = [t for t in app.errors.get(mid, []) if now - t < ERR_WINDOW] + [now]
            app.errors[mid] = hits
            if not os.path.isfile(m["path"]):
                c.execute("UPDATE media SET available=0 WHERE id=?", (mid,))
                action = "marked-missing"
            elif certain or len(hits) >= ERR_LIMIT:   # "certain": the page saw sound but no picture, no need to wait for repeats
                c.execute("UPDATE media SET playable=0 WHERE id=?", (mid,))  # a rescan re-evaluates it
                action = "marked-unplayable"
            else:
                return {"action": "retry"}
            c.commit()
            S.extend_all(c, now, app.horizon(), rebuild=True, tz=app.tz)
            return {"action": action}

        def media(self, mid):
            try:
                mid = int(mid)
            except (TypeError, ValueError):
                return self.send_json({"error": "invalid media id"}, 400)
            if mid <= 0:
                return self.send_json({"error": "invalid media id"}, 400)
            c = app.db()
            try:
                m = c.execute("SELECT path FROM media WHERE id=? AND available=1", (mid,)).fetchone()
            finally:
                c.close()
            if m is None or not os.path.isfile(m["path"]):
                return self.send_json({"error": "not found"}, 404)
            path, size = m["path"], os.path.getsize(m["path"])
            start, end, code = 0, size - 1, 200
            rng = self.headers.get("Range")
            if rng:
                if not rng.startswith("bytes=") or "," in rng:
                    self.send_response(416)
                    self.send_header("Content-Range", f"bytes */{size}")
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                    return
                a, _, b = rng[6:].partition("-")
                try:
                    if a == "" and b:
                        suffix = int(b)
                        if suffix <= 0:
                            raise ValueError("invalid suffix range")
                        start = max(0, size - suffix)
                    elif a != "":
                        start = int(a)
                        end = min(size - 1, int(b)) if b else size - 1
                    else:
                        raise ValueError("invalid range")
                except ValueError:
                    start, end = 1, 0
                if start > end or start >= size:
                    self.send_response(416)
                    self.send_header("Content-Range", f"bytes */{size}")
                    self.send_header("Content-Length", "0")
                    self.end_headers()
                    return
                code = 206
            self.send_response(code)
            self.send_header("Content-Type", VIDEO_MIME.get(os.path.splitext(path)[1].lower()) or mimetypes.guess_type(path)[0] or "application/octet-stream")
            self.send_header("Accept-Ranges", "bytes")
            self.send_header("Content-Length", str(end - start + 1))
            if code == 206:
                self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
            self.end_headers()
            with open(path, "rb") as f:
                f.seek(start)
                left = end - start + 1
                while left > 0:
                    chunk = f.read(min(262144, left))
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    left -= len(chunk)
